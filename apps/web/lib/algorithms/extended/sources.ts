import type { CodeLanguage, LineMap } from "../types";

type MarkedLine = string | [number | number[], string];
export interface AdditionalSources {
  code: Partial<Record<CodeLanguage, string>>;
  lineMaps: Partial<Record<CodeLanguage, LineMap>>;
}

/** Mark semantic C statements with their equivalent primary TypeScript line. */
function sources(javascript: string[], c: MarkedLine[]): AdditionalSources {
  const cMap: LineMap = {};
  const cLines = c.map((entry, index) => {
    if (typeof entry === "string") return entry;
    for (const line of Array.isArray(entry[0]) ? entry[0] : [entry[0]]) {
      const previous = cMap[line];
      cMap[line] =
        previous === undefined
          ? index + 1
          : [...(Array.isArray(previous) ? previous : [previous]), index + 1];
    }
    return entry[1];
  });
  return {
    code: { javascript: javascript.join("\n"), c: cLines.join("\n") },
    lineMaps: {
      javascript: Object.fromEntries(
        javascript.map((_, index) => [index + 1, index + 1]),
      ),
      c: cMap,
    },
  };
}

